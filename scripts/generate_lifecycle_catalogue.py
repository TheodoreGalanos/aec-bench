#!/usr/bin/env python3
# ABOUTME: Generates the committed lifecycle owner composition module.
# ABOUTME: Uses an explicit owner list so discovery is deterministic and reviewable.

from __future__ import annotations

import argparse
from pathlib import Path

OWNER_IMPORTS: tuple[tuple[str, str, str, str], ...] = (
    (
        "drainage-model-evidence-lifecycle-review",
        "aec_bench.lifecycles.stormwater_design.drainage_model",
        "LIFECYCLE_DESCRIPTOR",
        "DRAINAGE_MODEL_DESCRIPTOR",
    ),
    (
        "facade-submittal-review-lifecycle",
        "aec_bench.lifecycles.structural_review.facade_submittal",
        "LIFECYCLE_DESCRIPTOR",
        "FACADE_SUBMITTAL_DESCRIPTOR",
    ),
    (
        "hydraulic-design-response-lifecycle-review",
        "aec_bench.lifecycles.stormwater_design.design_response",
        "LIFECYCLE_DESCRIPTOR",
        "DESIGN_RESPONSE_DESCRIPTOR",
    ),
    (
        "hydraulic-interaction-lifecycle-review",
        "aec_bench.lifecycles.stormwater_design.hydraulic_review",
        "LIFECYCLE_DESCRIPTOR",
        "HYDRAULIC_REVIEW_DESCRIPTOR",
    ),
)

_HEADER = """# Generated by scripts/generate_lifecycle_catalogue.py. Do not edit by hand.
# ABOUTME: Loads the checked-in lifecycle composition generated from concrete owners.
# ABOUTME: Keeps template discovery explicit, readable, and stable without a mutable registry.

from __future__ import annotations

"""


def render_catalogue(
    owner_imports: tuple[tuple[str, str, str, str], ...] = OWNER_IMPORTS,
) -> str:
    """Render the generated lifecycle catalogue from the explicit owner list."""

    ordered_imports = tuple(sorted(owner_imports, key=lambda owner_import: owner_import[0]))
    imports = sorted(
        [f"from {module} import {attribute} as {alias}" for _, module, attribute, alias in ordered_imports]
        + ["from aec_bench.lifecycles.runtime.definition import LifecycleDefinition, LifecycleOwnerDescriptor"]
    )
    import_block = "\n".join(imports)
    descriptors = ",\n".join(f"    {alias}" for _, _, _, alias in ordered_imports)
    return (
        f"{_HEADER}{import_block}\n\n"
        "# This tuple is generated by scripts/generate_lifecycle_catalogue.py. Keep entries sorted by template_id.\n"
        "LIFECYCLE_DESCRIPTORS: tuple[LifecycleOwnerDescriptor, ...] = (\n"
        f"{descriptors},\n"
        ")\n\n\n"
        "def load_lifecycle_definitions() -> tuple[LifecycleDefinition, ...]:\n"
        '    """Load the current lifecycle definitions in generated stable order."""\n\n'
        "    definitions = tuple(descriptor.load() for descriptor in LIFECYCLE_DESCRIPTORS)\n"
        "    template_ids = tuple(definition.metadata.template_id for definition in definitions)\n"
        "    if len(template_ids) != len(set(template_ids)):\n"
        '        raise ValueError("generated lifecycle catalogue template IDs must be unique")\n'
        "    return tuple(sorted(definitions, key=lambda definition: definition.metadata.template_id))\n\n\n"
        '__all__ = ("LIFECYCLE_DESCRIPTORS", "load_lifecycle_definitions")\n'
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("src/aec_bench/lifecycles/generated_catalogue.py"),
        help="Generated module path.",
    )
    args = parser.parse_args()
    args.output.write_text(render_catalogue(), encoding="utf-8")


if __name__ == "__main__":
    main()
