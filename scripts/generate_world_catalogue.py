#!/usr/bin/env python3
# ABOUTME: Generates the committed Interactive World owner composition module.
# ABOUTME: Uses an explicit owner list so discovery is deterministic and reviewable.

from __future__ import annotations

import argparse
from pathlib import Path

OWNER_IMPORTS: tuple[tuple[str, str, str, str], ...] = (
    (
        "dam-seepage-monitoring",
        "aec_bench.worlds.monitoring.dam_seepage",
        "WORLD_DESCRIPTOR",
        "DAM_SEEPAGE_DESCRIPTOR",
    ),
    (
        "wastewater-pump-station-stewardship.v1",
        "aec_bench.worlds.stewardship.wastewater_pump_station",
        "WORLD_DESCRIPTOR",
        "PUMP_STATION_DESCRIPTOR",
    ),
)

_HEADER = """# Generated by scripts/generate_world_catalogue.py. Do not edit by hand.
# ABOUTME: Loads the checked-in composition generated from concrete world owners.
# ABOUTME: Keeps runtime discovery explicit, readable, and stable without a mutable registry.

from __future__ import annotations

"""


def render_catalogue(
    owner_imports: tuple[tuple[str, str, str, str], ...] = OWNER_IMPORTS,
) -> str:
    """Render the generated catalogue from the explicit owner import list."""

    ordered_imports = tuple(sorted(owner_imports, key=lambda owner_import: owner_import[0]))
    imports = sorted(
        [f"from {module} import {attribute} as {alias}" for _, module, attribute, alias in ordered_imports]
        + [
            "from aec_bench.worlds.runtime.definition import "
            "InteractiveWorldDefinition, InteractiveWorldOwnerDescriptor"
        ]
    )
    import_block = "\n".join(imports)
    descriptors = ",\n".join(f"    {alias}" for _, _, _, alias in ordered_imports)
    return (
        f"{_HEADER}{import_block}\n\n"
        "# This tuple is generated by scripts/generate_world_catalogue.py. Keep entries sorted by task_world_id.\n"
        "WORLD_DESCRIPTORS: tuple[InteractiveWorldOwnerDescriptor, ...] = (\n"
        f"{descriptors},\n"
        ")\n\n\n"
        "def load_world_definitions() -> tuple[InteractiveWorldDefinition, ...]:\n"
        '    """Load the current definitions in the generated stable order."""\n\n'
        "    return tuple(descriptor.load() for descriptor in WORLD_DESCRIPTORS)\n\n\n"
        '__all__ = ("WORLD_DESCRIPTORS", "load_world_definitions")\n'
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("src/aec_bench/worlds/generated_catalogue.py"),
        help="Generated module path.",
    )
    args = parser.parse_args()
    args.output.write_text(render_catalogue(), encoding="utf-8")


if __name__ == "__main__":
    main()
